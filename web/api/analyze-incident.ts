import type { VercelRequest, VercelResponse } from "@vercel/node";

export default async function handler(req: VercelRequest, res: VercelResponse) {
  // CORS configuration
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type, Authorization");

  if (req.method === "OPTIONS") {
    return res.status(200).end();
  }

  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed. Use POST." });
  }

  const geminiApiKey = process.env.GEMINI_API_KEY;
  if (!geminiApiKey) {
    return res.status(500).json({
      error: "Server configuration error: Missing GEMINI_API_KEY."
    });
  }

  try {
    const { narrative, language = "en" } = req.body;

    if (!narrative || typeof narrative !== "string" || narrative.trim().length < 5) {
      return res.status(400).json({ error: "A valid incident narrative is required." });
    }

    const geminiEndpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${geminiApiKey}`;

    const systemPrompt = `
You are an expert South African legal and trauma-informed advocate specializing in the Domestic Violence Act 116 of 1998 (amended by Act 14 of 2021).
A domestic abuse survivor has provided a spoken or typed testimony in their own words. The testimony may be written in English, isiZulu, isiXhosa, Sesotho, or Afrikaans:

"""${narrative}"""

Your mission:
1. Translate and format this into an objective, factual, sworn affidavit statement suitable for submission to the Clerk of the South African Magistrates' Court under Form 2 (Application for Protection Order).
2. Categorize the forms of domestic abuse documented under the Act:
   - Physical abuse
   - Sexual abuse
   - Emotional, verbal and psychological abuse
   - Economic abuse
   - Intimidation / Harassment / Stalking
   - Damage to property
   - Entry into the applicant's residence without consent
3. Calculate an empirical Danger Assessment Index (DAI) score between 1 and 100 based on lethal risk indicators:
   - Use of or threats with dangerous weapons
   - Threats to kill or history of strangulation / choking
   - Escalation in frequency or severity
   - Forced sexual acts or coercive control
4. Recommend specific statutory terms of relief to ask the Magistrate (e.g., Respondent prohibited from entering shared residence, SAPS ordered to seize firearm, interim maintenance order).

Strictly respond with a valid JSON object matching this schema:
{
  "courtAffidavit": "string (the complete, objective formal affidavit narrative for the court)",
  "abuseCategories": ["string"],
  "dangerScore": number (1 to 100),
  "riskTier": "LOW" | "MODERATE" | "HIGH" | "CRITICAL",
  "recommendedCourtRelief": ["string"],
  "supportMessage": "string (empathetic, affirming message to the survivor in their original language)"
}
`;

    const response = await fetch(geminiEndpoint, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [{ parts: [{ text: systemPrompt }] }],
        generationConfig: {
          temperature: 0.2,
          responseMimeType: "application/json"
        }
      })
    });

    if (!response.ok) {
      const errText = await response.text();
      console.error("Google AI Studio Gemini API error:", errText);
      return res.status(502).json({ error: "Failed to communicate with Google AI Studio." });
    }

    const data = await response.json();
    const generatedRaw = data.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!generatedRaw) {
      return res.status(500).json({ error: "No response generated by Gemini." });
    }

    const parsed = JSON.parse(generatedRaw);
    return res.status(200).json(parsed);
  } catch (error: any) {
    console.error("Vercel Gemini Serverless function exception:", error);
    return res.status(500).json({ error: error.message || "Internal server error" });
  }
}
